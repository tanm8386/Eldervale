export const xpForLevel = (level) => Math.round(80 * Math.pow(level, 1.45));
export const classStats = (player) => {
  const base = CLASSES[player.classId] || CLASSES.warrior;
  const level = player.level || 1;
  const weapon = ITEMS[player.equipment?.weapon] || {};
  const armor = ITEMS[player.equipment?.armor] || {};
  const charm = ITEMS[player.equipment?.charm] || {};
  return {
    maxHealth: base.health + (level - 1) * 18,
    maxMana: base.mana + (level - 1) * 8,
    damage: base.damage + (level - 1) * 4 + (weapon.power || 0) + (charm.power || 0),
    armor: base.armor + (level - 1) + (armor.armor || 0) + (charm.armor || 0),
    speed: base.speed,
    range: base.range,
  };
};
