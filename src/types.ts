export type ClassId = 'warrior' | 'archer' | 'mage';
export type Appearance = {
  skin: number;
  hair: number;
  style: number;
  outfit: number;
  body: number;
};
export type Character = { name: string; classId: ClassId; appearance: Appearance };
export type PublicPlayer = Character & {
  id: string;
  x: number;
  y: number;
  direction: number;
  moving: boolean;
  health: number;
  maxHealth: number;
  level: number;
  attackUntil: number;
  guardUntil: number;
  hasteUntil: number;
};
export type Player = PublicPlayer & {
  mana: number;
  maxMana: number;
  damage: number;
  armor: number;
  speed: number;
  range: number;
  xp: number;
  nextLevelXp: number;
  gold: number;
  inventory: { id: string; count: number }[];
  equipment: { weapon: string; armor: string; charm: string | null };
  questIndex: number;
  questAccepted: boolean;
  questProgress: Record<string, number>;
  completedQuests: string[];
  discovered: string[];
  kills: number;
  cooldowns: number[];
  potionUntil: number;
  target: string | null;
};
export type Mob = {
  id: string;
  type: 'slime' | 'mushroom' | 'wolf' | 'guardian';
  x: number;
  y: number;
  health: number;
  maxHealth: number;
  direction: number;
  moving: boolean;
  stunUntil: number;
  attackAt: number;
  target: string | null;
  respawnAt: number;
};
export type Herb = { id: string; x: number; y: number; available: boolean };
export type GameEvent = {
  id: number;
  at: number;
  kind: string;
  x: number;
  y: number;
  amount?: number | string;
  critical?: boolean;
  playerId?: string;
  targetId?: string;
  classId?: ClassId;
  index?: number;
  fromX?: number;
  fromY?: number;
  targetX?: number;
  targetY?: number;
  direction?: number;
  mana?: boolean;
  monster?: string;
};
export type WorldState = {
  type: 'state';
  time: number;
  online: number;
  self: Player;
  players: PublicPlayer[];
  mobs: Mob[];
  herbs: Herb[];
  events: GameEvent[];
};
export type ChatMessage = {
  type: 'chat';
  channel: 'world' | 'local';
  name: string;
  text: string;
  at: number;
  system?: boolean;
  playerId?: string;
};
export type Notice = { id: number; text: string; tone: string };
export type Send = (message: Record<string, unknown>) => void;
export type Panel = 'inventory' | 'journal' | 'map' | 'settings' | 'help' | 'players' | null;
export type AssetMeta = { w: number; h: number; frames: number; columns: number };
export type Item = {
  name: string;
  type: string;
  icon: string;
  description: string;
  price?: number;
  class?: ClassId;
  power?: number;
  armor?: number;
  rarity: string;
  sell?: number;
  heal?: number;
  mana?: number;
};
